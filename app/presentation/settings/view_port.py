"""Public view surface used by the presenter, without concrete UI imports.

Payload types are generic during the staged migration: the current presenter
still passes domain snapshots, while phase three will bind the display contracts.
This keeps the port honest about the live interface without exposing a schema.
The current QObject presenter also requires a QObject parent at assembly time;
that lifecycle detail is intentionally not part of this data-facing protocol.
"""
from typing import Callable, Protocol, TypeVar

from app.contracts.settings import CloseChoice, ConnectionInputs, TestTarget


class ViewEvent(Protocol):
    def connect(self, callback: Callable[..., object]) -> object: ...


SnapshotT = TypeVar("SnapshotT", contravariant=True)
GroupsT = TypeVar("GroupsT", contravariant=True)
FeedbackT = TypeVar("FeedbackT", contravariant=True)
GroupT = TypeVar("GroupT", contravariant=True)
KeyT = TypeVar("KeyT", contravariant=True)


class SettingsView(Protocol[SnapshotT, GroupsT, FeedbackT, GroupT, KeyT]):
    settings_changed: ViewEvent
    groups_changed: ViewEvent
    apply_requested: ViewEvent
    cancel_requested: ViewEvent
    clear_history_requested: ViewEvent
    close_requested: ViewEvent
    closed: ViewEvent
    legacy_test_requested: ViewEvent
    group_test_requested: ViewEvent
    add_group_requested: ViewEvent
    add_key_requested: ViewEvent
    delete_group_requested: ViewEvent

    def load_snapshot(self, snapshot: SnapshotT) -> None: ...
    def load_groups(self, groups: GroupsT, enabled: bool, error: str | None) -> None: ...
    def set_personality_options(self, options: dict[str, str]) -> None: ...
    def show_group_feedback(self, feedback: FeedbackT) -> None: ...
    def show_dirty_state(self, dirty: bool) -> None: ...
    def show_saved(self) -> None: ...
    def commit_pending_input(self) -> None: ...
    def add_api_group(self, group: GroupT) -> None: ...
    def add_api_key(self, group_id: str, entry: KeyT) -> None: ...
    def remove_api_group(self, group_id: str) -> None: ...
    def connection_inputs(self) -> ConnectionInputs: ...
    def show_test_started(self, target: TestTarget) -> None: ...
    def show_test_finished(self, target: TestTarget, message: str) -> None: ...
    def show_warning(self, title: str, message: str) -> None: ...
    def confirm_clear_history(self) -> bool: ...
    def show_history_cleared(self) -> None: ...
    def confirm_group_delete(self, active: bool) -> bool: ...
    def confirm_close(self) -> CloseChoice: ...
    def close_without_prompt(self) -> None: ...
